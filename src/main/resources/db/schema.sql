-- 由开发者手工执行，启动时不自动执行。
-- 状态：1 启用（项目为正常），2 停用（项目为已关闭）。时间均为毫秒时间戳。

create table account (
    id bigint generated by default as identity primary key,
    account varchar(64) not null,
    password_hash varchar(100) not null,
    username varchar(64) not null,
    status smallint not null default 1,
    remark varchar(128) not null default '',
    last_login_at bigint null,
    last_project_id bigint null,
    created_at bigint not null,
    updated_at bigint not null,
    constraint uk_account_account unique (account)
);

create table project (
    id bigint generated by default as identity primary key,
    app_key varchar(64) not null,
    name varchar(64) not null,
    description varchar(128) not null default '',
    status smallint not null default 1,
    created_at bigint not null,
    updated_at bigint not null,
    constraint uk_project_app_key unique (app_key)
);

-- role_type：1 平台角色，2 角色模板，3 项目角色。项目角色必须有 project_id，其余为空。
create table role (
    id bigint generated by default as identity primary key,
    role_type smallint not null,
    project_id bigint null,
    template_id bigint null,
    name varchar(32) not null,
    code varchar(64) not null,
    description varchar(128) not null default '',
    status smallint not null default 1,
    built_in boolean not null default false,
    created_at bigint not null,
    updated_at bigint not null,
    constraint fk_role_project foreign key (project_id) references project (id),
    constraint ck_role_project check ((role_type = 3) = (project_id is not null))
);

create unique index uk_role_name on role (role_type, coalesce(project_id, 0), name);
create unique index uk_role_code on role (role_type, coalesce(project_id, 0), code);

create table account_role (
    account_id bigint not null,
    role_id bigint not null,
    primary key (account_id, role_id),
    constraint fk_account_role_account foreign key (account_id) references account (id),
    constraint fk_account_role_role foreign key (role_id) references role (id)
);

create table project_user (
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    account_id bigint not null,
    role_id bigint not null,
    created_at bigint not null,
    constraint uk_project_user_project_account unique (project_id, account_id),
    constraint fk_project_user_project foreign key (project_id) references project (id),
    constraint fk_project_user_account foreign key (account_id) references account (id),
    constraint fk_project_user_role foreign key (role_id) references role (id)
);

create index idx_project_user_account on project_user (account_id);

alter table account add constraint fk_account_last_project foreign key (last_project_id) references project (id);

-- scope：1 平台，2 项目。只在顶级目录选择，子项跟随上级。
create table menu (
    id bigint primary key,
    parent_id bigint null,
    menu_type smallint not null,
    scope smallint not null,
    name varchar(64) not null,
    icon varchar(64) not null default '',
    route_name varchar(64) not null default '',
    route_path varchar(128) not null default '',
    status smallint not null,
    hidden boolean not null default false,
    built_in boolean not null default false,
    sort_order integer not null default 0,
    created_at bigint not null,
    updated_at bigint not null,
    constraint fk_menu_parent foreign key (parent_id) references menu (id)
);

create index idx_menu_parent on menu (parent_id, sort_order, id);

create table role_menu (
    role_id bigint not null,
    menu_id bigint not null,
    primary key (role_id, menu_id),
    constraint fk_role_menu_role foreign key (role_id) references role (id),
    constraint fk_role_menu_menu foreign key (menu_id) references menu (id)
);

